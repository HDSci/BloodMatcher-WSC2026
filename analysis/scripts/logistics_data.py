def analyze_scenario_statistics(
    files_dict, 
    logistics_graph, 
    id_to_name, 
    day_order, 
    warm_up=42, 
    horizon=42,
    date_col=0, 
    src_col=1, 
    dst_col=2, 
    unit_col=3,
    pat_grp_col=None,
    move_reason=None,
    disaggregate=False  # New flag for Day/Time breakdown
):
    """
    Processes .npz scenarios. 
    If disaggregate=True: Results are broken down by specific departure day/time.
    If disaggregate=False: Results are aggregated by Origin-Destination location pair.
    """
    
    # 1. Internal Path Cache
    def _build_cache():
        cache = {}
        locations = list(id_to_name.values())
        for src_day in day_order:
            for src_loc in locations:
                src_node = f"{src_loc}-Blood Matching-{src_day}-08:00:00"
                try:
                    paths = nx.single_source_dijkstra_path(logistics_graph, src_node, weight='weight')
                    lengths = nx.single_source_dijkstra_path_length(logistics_graph, src_node, weight='weight')
                    for dst_loc in locations:
                        if src_loc == dst_loc: continue
                        target, min_d = None, float('inf')
                        for d_day in day_order:
                            d_node = f"{dst_loc}-Blood Matching-{d_day}-08:00:00"
                            if d_node in lengths and lengths[d_node] < min_d:
                                min_d, target = lengths[d_node], d_node
                        cache[(src_loc, dst_loc, src_day)] = paths.get(target)
                except: continue
        return cache

    path_cache = _build_cache()
    scenario_results = {}
    weeks_in_horizon = (horizon - warm_up) / 7

    for s_name, f_path in tqdm.tqdm(files_dict.items(), desc="Processing Scenarios", position=0,):
        if f_path.endswith('_output.tsv'):
            f_path = f_path.replace('_output.tsv', '_moves.npz')
        
        if not os.path.exists(f_path): continue

        data = np.load(f_path)
        replications = data.files
        num_reps = len(replications)
        
        # Key: (u, v) edge -> Value: np.array of size num_reps
        rep_data = {} 

        for idx, rep_key in tqdm.tqdm(enumerate(replications), desc="Processing Replications", position=1,
                                      leave=False, total=num_reps,):
            moves = data[rep_key]
            mask = (moves[:, date_col] > warm_up) & (moves[:, date_col] <= (horizon))
            ss_moves = moves[mask]
            
            if type(pat_grp_col) == int and type(move_reason) == int:
                ss_moves = ss_moves[ss_moves[:, pat_grp_col] == move_reason]

            for row in ss_moves:
                day_val, s_id, d_id = int(row[date_col]), int(row[src_col]), int(row[dst_col])
                day_name = day_order[(day_val - 1) % 7]
                src_name, dst_name = id_to_name[s_id], id_to_name[d_id]
                
                path = path_cache.get((src_name, dst_name, day_name))
                if path:
                    for i in range(len(path) - 1):
                        edge = (path[i], path[i+1])
                        u_loc, v_loc = edge[0].split('-')[0], edge[1].split('-')[0]
                        
                        if u_loc != v_loc: # Transport leg check
                            if edge not in rep_data:
                                rep_data[edge] = np.zeros(num_reps)
                            rep_data[edge][idx] += 1

        # 2. Aggregation Logic
        temp_list = []
        for (u, v), totals_array in rep_data.items():
            # Parse node strings: "Location-Type-Day-Time"
            u_parts = u.split('-')
            v_parts = v.split('-')
            
            temp_list.append({
                'Origin': u_parts[0],
                'Destination': v_parts[0],
                'Dep_Day': u_parts[2],
                'Dep_Time': u_parts[3],
                'Weekly_Averages': totals_array / weeks_in_horizon
            })

        df_raw = pd.DataFrame(temp_list)
        
        if disaggregate:
            # Group by specific time-expanded edge
            group_cols = ['Origin', 'Destination', 'Dep_Day', 'Dep_Time']
        else:
            # Group by physical route only
            group_cols = ['Origin', 'Destination']

        # Custom aggregation to handle the numpy arrays correctly
        final_rows = []
        for name, group in df_raw.groupby(group_cols):
            # Sum the weekly averages across all trips in that group (for all reps)
            combined_reps = np.sum(np.stack(group['Weekly_Averages'].values), axis=0)
            
            row = {
                'Origin': name[0] if disaggregate else name[0],
                'Destination': name[1] if disaggregate else name[1],
                'Mean_Weekly_Units': np.mean(combined_reps),
                'Std_Error': stats.sem(combined_reps),
                'n_reps': num_reps,
                'Std_Dev': np.std(combined_reps,),
            }
            if disaggregate:
                row['Dep_Day'] = name[2]
                row['Dep_Time'] = name[3]
            
            final_rows.append(row)

        scenario_results[s_name] = pd.DataFrame(final_rows).sort_values('Mean_Weekly_Units', ascending=False)
        data.close()

    return scenario_results


def aggregate_disaggregated_results(df, level='route'):
    """
    Aggregates disaggregated leg data while properly propagating Mean, 
    Standard Error (SEM), and Standard Deviation (SD).
    
    Parameters
    ----------
    df : pd.DataFrame
        The disaggregated DataFrame (output from analyze_scenario_statistics).
        Expected columns: ['Mean_Weekly_Units', 'Std_Error', 'Std_Dev', 'n_reps']
    level : str, optional ('route' or 'day')
        'route': Aggregates everything to Origin -> Destination.
        'day': Aggregates to Origin -> Destination -> Day.
        
    Returns
    -------
    pd.DataFrame
        Aggregated results with properly propagated statistics.
    """
    if 'Dep_Day' not in df.columns and 'Dep_Time' not in df.columns:
        print("DataFrame is already aggregated. No disaggregated columns found.")
        return df
    
    if level == 'day':
        group_cols = ['Origin', 'Destination', 'Dep_Day']
    elif level == 'route':
        group_cols = ['Origin', 'Destination']
    else:
        raise ValueError("Level must be 'day' or 'route'")

    # Error Propagation Logic:
    # 1. Sum of Means: μ_total = Σ μ_i
    # 2. Sum of Variances (for SD and SEM): σ_total = sqrt(Σ σ_i^2)
    def propagate_error(x):
        return np.sqrt(np.sum(np.square(x)))

    agg_funcs = {
        'Mean_Weekly_Units': 'sum',
        'Std_Error': propagate_error,
        'Std_Dev': propagate_error,
        'n_reps': 'first' # Sample size (replications) remains constant
    }

    # Tracking how many trips are being collapsed into this one row
    df = df.copy()
    df['Trips_Count'] = 1
    agg_funcs['Trips_Count'] = 'sum'

    aggregated_df = df.groupby(group_cols).agg(agg_funcs).reset_index()
    
    return aggregated_df.sort_values('Mean_Weekly_Units', ascending=False)


def plot_scenario_comparison(
    df_test, 
    df_bench, 
    pos=None,
    text_pos=None, 
    max_diff=None, # Crucial for cross-plot comparison
    metric_for_alpha='SEM', 
    pos_color='#e66101', 
    neg_color='#5e3c99',
    figsize=(12, 9), 
    dpi=300, 
    save_path=None,
    z_threshold=2.0,
    width_multiplier=1.0,
):
    """
    Plots differences between two scenarios. Use 'max_diff' to ensure 
    visual consistency across multiple plots (e.g., E02 vs L01 and E03 vs L01).
    """
    rng = np.random.default_rng(seed=42)  # For reproducibility

    if pos is None:
        pos = {
            'Newcastle': (6, 9), 'Lancaster': (3, 8), 'Manchester': (4, 7), 
            'Liverpool': (3, 7), 'Barnsley': (5.5, 7.2), 'Birmingham': (4.5, 5),
            'Filton': (3.5, 3), 'Oxford': (5, 3.5), 'Southampton': (5, 2),
            'Plymouth': (2.4, 1.85), 'Cambridge': (7, 4.5), 'Colindale': (5.7, 3.8),
            'Tooting': (6.8, 2.5), 'Basildon': (7.5, 3.5)
        }
        if text_pos is None:
            text_pos = {
                'Newcastle': (6, 9.15), 'Lancaster': (3, 8.15), 'Manchester': (4, 7.3),
                'Liverpool': (2.8, 7.1), 'Barnsley': (5.5, 7.35), 'Birmingham': (5, 5.15),
                'Filton': (3.2, 3.15), 'Oxford': (5.25, 3.), 'Southampton': (5, 1.5),
                'Plymouth': (2.4, 1.4), 'Cambridge': (7, 4.65), 'Colindale': (5.8, 4.2),
                'Tooting': (6.8, 2.), 'Basildon': (7.5, 3.),
            }

    # 1. Merge and calculate differences
    merged = pd.merge(df_test, df_bench, on=['Origin', 'Destination'], 
                      how='outer', suffixes=('_t', '_b')).fillna(0)
    
    merged['diff_mean'] = merged['Mean_Weekly_Units_t'] - merged['Mean_Weekly_Units_b']
    merged['diff_sem'] = np.sqrt(merged['Std_Error_t']**2 + merged['Std_Error_b']**2)
    merged['diff_sd'] = np.sqrt(merged['Std_Dev_t']**2 + merged['Std_Dev_b']**2)

    # If no global max_diff is provided, calculate from local data
    if max_diff is None:
        max_diff = merged['diff_mean'].abs().max() if not merged.empty else 1
    # Avoid divide-by-zero in linewidth scaling when all differences are zero.
    if max_diff <= 0:
        max_diff = 1

    def _line_width_from_diff(diff_value):
        rel_size = abs(diff_value) / max_diff
        return (rel_size * 12 + 0.5) * width_multiplier

    fig, ax = plt.subplots(figsize=figsize, dpi=dpi)
    
    # 2. Draw Nodes (Clean, white background to avoid clashing with Seaborn/Text)
    for loc, p in pos.items():
        ax.scatter(p[0], p[1], s=100, c='white', edgecolors='#333333', lw=0.8, zorder=10)
        if text_pos is None:
            ax.text(p[0], p[1]+0.15, loc, zorder=11, ha='center', va='bottom')
        else:
            ax.text(text_pos.get(loc, p)[0], text_pos.get(loc, p)[1], loc, zorder=11, ha='center', va='bottom')

    # 3. Draw Edges
    for _, row in merged.iterrows():
        if abs(row['diff_mean']) < 0.05: continue # Ignore trace differences
        
        u_p, v_p = np.array(pos[row['Origin']]), np.array(pos[row['Destination']])
        color = pos_color if row['diff_mean'] > 0 else neg_color
        
        # Line width is now anchored to the provided global max_diff
        # width = (abs(row['diff_mean']) / max_diff) * 10 + 0.5
        lw = _line_width_from_diff(row['diff_mean'])
        
        # Alpha/Transparency Logic
        if metric_for_alpha == 'SEM':
            z = abs(row['diff_mean']) / (row['diff_sem'] + 1e-9)
            alpha = np.clip(z / z_threshold, 0.1, 0.8)
        elif metric_for_alpha == 'STDEV':
            z = abs(row['diff_mean']) / (row['diff_sd'] + 1e-9)
            alpha = np.clip(z / z_threshold, 0.1, 0.8)
        else:
            alpha = 0.75

        # Connection style for bi-directional visibility
        # Curved arcs prevent 'London blob' overlap
        arc_rad = 0.2
        
        # Draw the main flow line (no arrow head)
        ax.annotate("", xy=v_p, xytext=u_p,
                    arrowprops=dict(arrowstyle="-", color=color, lw=lw, alpha=alpha,
                                    connectionstyle=f"arc3,rad={arc_rad}",
                                    shrinkA=8, shrinkB=8))

        # Draw a tiny segment in the middle with the arrowhead
        shrinkA_jitter = 25 * (0.6 + rng.random()/2)
        shrinkB_jitter = 40 * (0.8 + rng.random()/3)
        mid_arrow = FancyArrowPatch(
            u_p, v_p, 
            connectionstyle=f"arc3,rad={arc_rad}",
            arrowstyle='-|>,head_length=8,head_width=13',
            # arrowstyle='-|>',
            color=color,  # Black arrowhead for contrast
            lw=0.0,  # No line, just the arrowhead
            alpha=1,
            # mutation_scale=m_scale, 
            shrinkA=shrinkA_jitter, shrinkB=shrinkB_jitter  # No shrink so it stays in the middle
        )
        ax.add_patch(mid_arrow)

    # Thickness legend values include the current max_diff by construction.
    legend_diffs = [20, 100, 200, 400, 800]
    legend_handles = [
        Line2D([0], [0], color='#444444', lw=_line_width_from_diff(diff_val), alpha=0.9)
        for diff_val in legend_diffs
    ]
    legend_labels = [
        f" {diff_val:.0f}"
        for diff_val in legend_diffs
    ]
    ax.legend(
        legend_handles,
        legend_labels,
        title="Δ Mean weekly units",
        loc='upper left',
        bbox_to_anchor=(0.67, 0.88),
        frameon=True,
        framealpha=0.95,
        facecolor='white',
        edgecolor='#bfbfbf',
        fontsize=12,
        title_fontsize=15,
    )

    ax.set_axis_off()
    
    if save_path:
        plt.savefig(save_path, format='pdf', bbox_inches='tight', dpi=dpi)
    
    plt.show()
    return max_diff # Return it so you can use it for the next plot
